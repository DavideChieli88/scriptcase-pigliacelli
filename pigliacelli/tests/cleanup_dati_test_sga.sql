/*
    Cleanup dati TEST su Sgam (SQL Server) — DBeaver.
    Target: VETTORE/CODICE 99001..99099, NUMERO viaggio/cliente 990000..990099
    SOCIETA = 1 (inline, niente @variabili: DBeaver altrimenti dà errore 137).

    Usa "Execute SQL Script" / esegui tutto il file.
    Di default ROLLBACK: per applicare, scambia COMMIT/ROLLBACK in fondo.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;

BEGIN TRANSACTION;

-- --- Preview ---
SELECT 'T2BaseVettori' AS t, CODICE, RAGIONE_SOCIALE, ATTIVO
FROM T2BaseVettori
WHERE SOCIETA = 1
  AND CODICE BETWEEN 99001 AND 99099;

SELECT 'T2ViaggiVettori' AS t, ANNO, NUMERO, VETTORE, IMPORTO_UNITARIO, PARTENZA_DATA_ORA
FROM T2ViaggiVettori
WHERE SOCIETA = 1
  AND (VETTORE BETWEEN 99001 AND 99099 OR NUMERO BETWEEN 990000 AND 990099);

SELECT 'BaCliFor' AS t, CLIENTE_FORNITORE, CODICE, RAGIONE_SOCIALE, PARTITA_IVA
FROM BaCliFor
WHERE SOCIETA = 1
  AND CODICE BETWEEN 99001 AND 99099;

-- --- Delete ---
DELETE a
FROM T2ViaggiVettoriAddebiti a
INNER JOIN T2ViaggiVettori v
   ON v.SOCIETA = a.SOCIETA AND v.ANNO = a.ANNO AND v.NUMERO = a.NUMERO
WHERE v.SOCIETA = 1
  AND (v.VETTORE BETWEEN 99001 AND 99099 OR v.NUMERO BETWEEN 990000 AND 990099);

-- Figlio di CarichiScarichi (FK FkT2ViaggiClientiCarichiScarichiMerci_TESTATA)
DELETE m
FROM T2ViaggiClientiCarichiScarichiMerci m
INNER JOIN T2ViaggiVettoriClienti vc
   ON vc.SOCIETA = m.SOCIETA
  AND vc.CLIENTE_ANNO = m.ANNO
  AND vc.CLIENTE_FILIALE = m.FILIALE
  AND vc.CLIENTE_NUMERO = m.NUMERO
  AND vc.CLIENTE_NUMERO_CARICO_SCARICO = m.NUMERO_CARICO_SCARICO
INNER JOIN T2ViaggiVettori v
   ON v.SOCIETA = vc.SOCIETA AND v.ANNO = vc.ANNO AND v.NUMERO = vc.NUMERO
WHERE v.SOCIETA = 1
  AND (v.VETTORE BETWEEN 99001 AND 99099 OR v.NUMERO BETWEEN 990000 AND 990099);

DELETE cs
FROM T2ViaggiClientiCarichiScarichi cs
INNER JOIN T2ViaggiVettoriClienti vc
   ON vc.SOCIETA = cs.SOCIETA
  AND vc.CLIENTE_ANNO = cs.ANNO
  AND vc.CLIENTE_FILIALE = cs.FILIALE
  AND vc.CLIENTE_NUMERO = cs.NUMERO
  AND vc.CLIENTE_NUMERO_CARICO_SCARICO = cs.NUMERO_CARICO_SCARICO
INNER JOIN T2ViaggiVettori v
   ON v.SOCIETA = vc.SOCIETA AND v.ANNO = vc.ANNO AND v.NUMERO = vc.NUMERO
WHERE v.SOCIETA = 1
  AND (v.VETTORE BETWEEN 99001 AND 99099 OR v.NUMERO BETWEEN 990000 AND 990099);

DELETE vc
FROM T2ViaggiVettoriClienti vc
INNER JOIN T2ViaggiVettori v
   ON v.SOCIETA = vc.SOCIETA AND v.ANNO = vc.ANNO AND v.NUMERO = vc.NUMERO
WHERE v.SOCIETA = 1
  AND (v.VETTORE BETWEEN 99001 AND 99099 OR v.NUMERO BETWEEN 990000 AND 990099);

DELETE FROM T2ViaggiClienti
WHERE SOCIETA = 1
  AND NUMERO BETWEEN 990000 AND 990099;

DELETE FROM T2ViaggiVettori
WHERE SOCIETA = 1
  AND (VETTORE BETWEEN 99001 AND 99099 OR NUMERO BETWEEN 990000 AND 990099);

DELETE FROM BaCliFor
WHERE SOCIETA = 1
  AND CODICE BETWEEN 99001 AND 99099;

DELETE FROM T2BaseVettori
WHERE SOCIETA = 1
  AND CODICE BETWEEN 99001 AND 99099;

COMMIT TRANSACTION;
-- ROLLBACK TRANSACTION;
